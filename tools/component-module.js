/* Static delivery modules preserve source overrides rather than freezing sidecar defaults. */
function serialize(value,seen=new Set()){
 if(value===undefined)return'void 0';
 if(typeof value==='number'){if(Object.is(value,-0))return'-0';if(Number.isNaN(value))return'(0/0)';if(!Number.isFinite(value))return value<0?'(-1/0)':'(1/0)';}
 if(value===null||['string','number','boolean'].includes(typeof value))return JSON.stringify(value);
 if(typeof value!=='object')throw Error('Component module cannot serialize '+typeof value);
 if(seen.has(value))throw Error('Cyclic component definition');seen.add(value);
 let result;
 if(Array.isArray(value)){
  if(Object.getOwnPropertySymbols(value).length||Object.keys(value).some(key=>! /^(0|[1-9]\d*)$/.test(key)||Number(key)>=value.length))throw Error('Component module requires plain arrays');
  for(const key of Object.keys(value)){const d=Object.getOwnPropertyDescriptor(value,key);if(d.get||d.set)throw Error('Component module cannot serialize accessors');}
  const entries=[];for(let i=0;i<value.length;i++)entries.push(i in value?serialize(value[i],seen):'');
  result='['+entries.join(',')+(value.length&&!(value.length-1 in value)?',':'')+']';
 }else{
  const prototype=Object.getPrototypeOf(value);
  if(Object.prototype.toString.call(value)!=='[object Object]'||Object.getOwnPropertySymbols(value).length||prototype!==null&&(Object.getPrototypeOf(prototype)!==null||!Object.hasOwn(prototype,'constructor')||typeof prototype.constructor!=='function'||Function.prototype.toString.call(prototype.constructor)!==Function.prototype.toString.call(Object)))throw Error('Component module requires plain data');
  const entries=Object.keys(value).map(key=>{const d=Object.getOwnPropertyDescriptor(value,key);if(d.get||d.set)throw Error('Component module cannot serialize accessors');return(key==='__proto__'?'["__proto__"]':JSON.stringify(key))+':'+serialize(value[key],seen);});
  result='{'+entries.join(',')+'}';if(Object.getPrototypeOf(value)===null)result='Object.assign(Object.create(null),'+result+')';
 }
 seen.delete(value);return result;
}
function browserDefinition(demo,sidecar){
 if(!Object.hasOwn(demo,'_inlineMeta'))throw Error(demo.id+': metadata must be applied before module generation');
 const raw={...demo};
 for(const key of Object.keys(sidecar)){
  if(Object.hasOwn(demo._inlineMeta,key))raw[key]=demo._inlineMeta[key];else delete raw[key];
 }
 return raw;
}
function buildComponentModule(demo,sidecar,source){
 if(!/^js\/[\w.-]+\.js$/.test(source))throw Error('Invalid authoring module path');
 return'/* Generated by tools/build-registry.js from '+source+'. Do not edit. */\nINTRX.register('+serialize(browserDefinition(demo,sidecar))+');\n';
}
module.exports={serialize,browserDefinition,buildComponentModule};
